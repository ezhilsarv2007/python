"""Runs every program of Tasks 1-12, saves the full output of each task in TaskXX/output.txt
and puts the same output at the end of TaskXX/README.md.
Usage:  python run_all.py            (from the repository root)"""
import os
import subprocess
import sys

COMMANDS = {
    "Task01": ["task01_analysis.py"],
    "Task02": ["interactive_session.py", "task02_complete_code.py", "task02_alternatives.py"],
    "Task03": ["task03_constants.py"],
    "Task04": ["task04_expressions.py"],
    "Task05": ["task05_input.py"],
    "Task06": ["task06_functions.py"],
    "Task07": ["milkrate.py", "use_milkrate.py", "copied_functions_demo.py"],
    "Task08": ["algorithm.py"],
    "Task09": ["test_milk_calculator.py", "milk_calculator.py --file entries.csv", "task09_manual_vs_assert.py"],
    "Task10": ["task10_compare.py"],
    "Task11": ["task11_final_design.py"],
    "Task12": ["task12_design_challenge.py"],
}
MARK = "\n## Full output (generated by run_all.py)\n"

root = os.path.dirname(os.path.abspath(__file__))
for task, scripts in COMMANDS.items():
    folder = os.path.join(root, task)
    parts = []
    for command in scripts:
        proc = subprocess.run([sys.executable, *command.split()], cwd=folder, capture_output=True, text=True)
        parts.append(f"$ python {command}\n{proc.stdout}{proc.stderr}")
        if proc.returncode != 0:
            print(f"!! {task}: {command} failed (exit code {proc.returncode})")
    output = "\n".join(parts)
    with open(os.path.join(folder, "output.txt"), "w", encoding="utf-8") as f:
        f.write(output)
    readme = os.path.join(folder, "README.md")
    text = open(readme, encoding="utf-8").read().split(MARK)[0]
    with open(readme, "w", encoding="utf-8") as f:
        f.write(text + MARK + "\n<details><summary>Click to expand the output</summary>\n\n```text\n" + output + "\n```\n\n</details>\n")
    print(f"{task}: output saved ({len(scripts)} program(s))")
